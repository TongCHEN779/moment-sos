"""Write results/e10_notes.md from results/e10a.json, results/e10b.json (numbers copied programmatically)."""
import json, numpy as np
a = json.load(open("results/e10a.json")); b = json.load(open("results/e10b.json")); bs = json.load(open("results/e10b_summary.json"))
L = []
L.append("# E10 notes: ALM on MAX-CUT (E10a) and instance variability (E10b)\n")
L.append("All numbers below are copied from `experiments/results/e10a.json` and `experiments/results/e10b.json`.\n")
L.append("**Timing caveat.** Everything ran on the shared 14-core machine while three other tracks were running "
         "(1-minute load average between 13 and 94 during the runs; the `loadavg` field of every record stores the value "
         "at the end of the run). Each run used 3 BLAS threads. Wall-clock times are therefore inflated and noisy by a factor "
         "that varies between runs (the n=16 smoothing run took 5.0 s in an isolated pilot and 29.2 s inside E10a); the "
         "`cpu_time` field (process CPU seconds) is the more robust quantity and is tabulated next to the wall time. "
         "Comparisons *between* solvers at the same n are still meaningful in order of magnitude only.\n")
L.append("## What was run\n")
L.append("* `msos/solvers.py::alm` -- NumPy port of `moment_sos.solve_alm` (appended; existing functions untouched). "
         "Validated by `tests/test_alm.py`: Petersen r=2 and disk r=2 agree with `moment_sos.solve_alm` on the identically normalised "
         "problem to < 1e-6 and with the interior-point reference (Clarabel) to < 1e-5; the inner augmented-Lagrangian gradient "
         "passes a finite-difference check (rel. error 5e-10).\n"
         "* E10a (`experiments/e10a_alm_maxcut.py`): order-2 MAX-CUT on `networkx.random_regular_graph(3, n, seed=1)`, n = 16, 20, 24, 30; "
         "solvers: smoothing + L-BFGS (`lbfgs_continuation`, iters_per_stage=500) and `alm` with rho0 in {100, 300, 1000}; "
         "time limit 600 s (900 s for n=30); every run in its own subprocess (peak RSS per run). For ALM the certificate U(theta) is "
         "evaluated at every outer iterate and additionally every 20 inner evaluations (`cert_every=20`, ~5% overhead) so that the "
         "time-to-gap has a fine resolution; the default `cert_every=0` mirrors moment_sos exactly.\n"
         "* E10b (`experiments/e10b_variability.py`): five random 3-regular graphs per size (seeds 1..5), n = 16, 20, 24, smoothing solver with the "
         "paper settings; best cut by brute force for all 15 instances (n=24 brute force took < 1 min, so the 2000-restart local search was only "
         "used as a cross-check); Clarabel interior-point reference where it finished.\n"
         "* Tables: `tables_e10a.tex`, `tables_e10b.tex` (generated by `experiments/make_tables_e10.py`, which also writes `figures/alm_maxcut.pdf`).\n")
L.append("## E10a: reference values\n")
for n, r in sorted(a["refs"].items(), key=lambda kv: int(kv[0])):
    L.append(f"* n={n}: ref = {r['ref']}, cut = {r['cut']} ({r['cut_method']}), source: {r['source']}"
             + (f"; Clarabel value {r['clarabel_value']} in {r['clarabel_time']:.0f} s" if r.get('clarabel_value') is not None else "")
             + (f"; {r['clarabel_note']}" if r.get('clarabel_note') else "")
             + (f"; confirmed by {r['confirmed_by']}" if r.get('confirmed_by') else "")
             + ("; PROVISIONAL" if r.get("provisional") else ""))
L.append("\n## E10a: key numbers (wall-clock seconds to a certified gap; `--` = not reached)\n")
L.append("| n | solver | t(1e-1) | t(1e-2) | t(1e-3) | t(1e-4) | final gap | wall s | CPU s | evals | outer | peak RSS GiB | status |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
f = lambda v: "--" if v is None else f"{v:.1f}"
for r in sorted(a["runs"], key=lambda r: (r["n"], r["solver"] != "smoothing", r["rho0"])):
    lab = "smoothing" if r["solver"] == "smoothing" else f"ALM rho0={int(r['rho0'])}"
    tg = r["t_gap"]
    L.append(f"| {r['n']} | {lab} | {f(tg['1e-01'])} | {f(tg['1e-02'])} | {f(tg['1e-03'])} | {f(tg['1e-04'])} | {r['final_gap']:.1e} | "
             f"{r['final_time']:.0f} | {r.get('cpu_time', float('nan')):.0f} | {r['evals']} | {r.get('outer_iters') or '--'} | {r['rss_gib']:.2f} | {r['status']} |")
# fastest to 1e-3 per n
L.append("\nFastest solver to a certified gap of 1e-3 (wall clock):\n")
for n in sorted({r["n"] for r in a["runs"]}):
    rr = [r for r in a["runs"] if r["n"] == n and r["t_gap"]["1e-03"] is not None]
    if rr:
        w = min(rr, key=lambda r: r["t_gap"]["1e-03"])
        lab = "smoothing" if w["solver"] == "smoothing" else f"ALM rho0={int(w['rho0'])}"
        L.append(f"* n={n}: {lab} ({w['t_gap']['1e-03']:.1f} s); reached 1e-4: " +
                 (", ".join(("smoothing" if r["solver"] == "smoothing" else f"ALM rho0={int(r['rho0'])}") + f" ({r['t_gap']['1e-04']:.1f} s)"
                            for r in a["runs"] if r["n"] == n and r["t_gap"]["1e-04"] is not None) or "none"))
    else:
        L.append(f"* n={n}: no solver reached 1e-3 within the time limit")
L.append("\n## E10b: key numbers\n")
L.append("| n | seed | wall s | CPU s | evals | U | floor U | best cut (method) | certified | margin | IPM value | IPM wall s |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in sorted(b["rows"], key=lambda r: (r["n"], r["seed"])):
    L.append(f"| {r['n']} | {r['seed']} | {r['time']:.1f} | {r.get('cpu_time', float('nan')):.1f} | {r['evals']} | {r['U']:.6f} | {r['floor_U']} | "
             f"{r['cut']} ({r['cut_method']}) | {r['certified']} | {r['margin']:.2e} | "
             f"{r['ipm_value']:.9f} | {r['ipm_time']:.0f} |" if 'ipm_value' in r else
             f"| {r['n']} | {r['seed']} | {r['time']:.1f} | {r.get('cpu_time', float('nan')):.1f} | {r['evals']} | {r['U']:.6f} | {r['floor_U']} | "
             f"{r['cut']} ({r['cut_method']}) | {r['certified']} | {r['margin']:.2e} | skipped | -- |")
L.append("\nSummary over seeds (mean [min, max]):\n")
for n, s in sorted(bs.items(), key=lambda kv: int(kv[0])):
    L.append(f"* n={n}: wall {s['time'][0]:.1f} [{s['time'][1]:.1f}, {s['time'][2]:.1f}] s; CPU {s['cpu_time'][0]:.1f} [{s['cpu_time'][1]:.1f}, {s['cpu_time'][2]:.1f}] s; "
             f"evaluations {s['evals'][0]:.0f} [{s['evals'][1]:.0f}, {s['evals'][2]:.0f}]; margin U - floor(U) {s['margin'][0]:.2e} [{s['margin'][1]:.2e}, {s['margin'][2]:.2e}]; "
             f"certified {s['certified']}/{s['count']}; IPM wall mean {s['ipm_time_mean'] if s['ipm_time_mean'] is None else round(s['ipm_time_mean'],1)} s; "
             f"IPM value rounds to the cut in all solved cases: {s['ipm_all_match']}")
open("results/e10_notes.md", "w").write("\n".join(L) + "\n")
print("\n".join(L[-12:]))
